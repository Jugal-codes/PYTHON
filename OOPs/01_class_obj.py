class Employee:         # Class_name Employee
    lang = "Python"     # Class attributes
    salary = 120000     # Class attributes


emp1 = Employee()       # Object instantiation  
emp1.name = "Amit"      # Instance attributes
print(emp1.name, emp1.lang, emp1.salary)

emp1 = Employee()       # Object instantiation  
emp1.name = "Amit"      # Instance attributes
emp1.lang = "JS"
print(emp1.name, emp1.lang, emp1.salary)

emp2 = Employee()
emp2.name = "Sumita"
print(emp2.salary, emp2.lang, emp2.name)




