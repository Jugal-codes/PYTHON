# Function is group of statements performing a specific task.
# Function definition : the part containing the exact set of instructions which are 
#                       executed during the function call 
# Function call : whenever we want to call a function, we put the name of the function
#                 with parentheses


# Syntax of function
def func1():        # function definition
    print("Hello")

func1()   # function call


# Example
def greet():
    print("Have a Good day!")

greet()